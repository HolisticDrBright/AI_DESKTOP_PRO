import { closeSync, existsSync, openSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ALIAS_PREFIX = "__e2e_order_";
const SPEC_NAME = /^[A-Za-z0-9_.-]+\.spec\.ts$/;

export function isOrderedAlias(name) {
  return name.startsWith(ALIAS_PREFIX) && name.endsWith(".spec.ts");
}

export function orderedAliasPlan(specs, direction) {
  if (direction !== "forward" && direction !== "reverse") {
    throw new Error(`Unknown E2E direction: ${direction}`);
  }
  if (specs.length === 0 || specs.some((name) => !SPEC_NAME.test(name) || isOrderedAlias(name))) {
    throw new Error("E2E spec names must be ordinary .spec.ts basenames");
  }
  if (new Set(specs).size !== specs.length) {
    throw new Error("E2E spec names must be unique");
  }
  return specs.map((spec, index) => {
    const alias = `${ALIAS_PREFIX}${direction}_${String(index).padStart(3, "0")}_${spec}`;
    return {
      spec,
      alias,
      content: `// Generated by check-e2e-order-independence.mjs; removed after the run.\nimport './${spec.slice(0, -3)}';\n`,
    };
  });
}

export function createOrderedAliases(directory, plan) {
  const created = [];
  try {
    for (const item of plan) {
      const path = join(directory, item.alias);
      if (existsSync(path)) {
        throw new Error(`Stale or occupied E2E order alias: ${path}`);
      }
      const handle = openSync(path, "wx");
      created.push({ path, content: item.content });
      try { writeFileSync(handle, item.content); }
      finally { closeSync(handle); }
    }
  } catch (error) {
    removeOrderedAliases(created);
    throw error;
  }
  return created;
}

export function removeOrderedAliases(created) {
  for (const item of created) {
    if (!existsSync(item.path)) continue;
    if (readFileSync(item.path, "utf8") !== item.content) {
      throw new Error(`Generated E2E alias changed during the run: ${item.path}`);
    }
    unlinkSync(item.path);
  }
}

export function listedSpecOrder(output) {
  const order = [];
  const seen = new Set();
  for (const line of output.split(/\r?\n/)) {
    const match = line.match(/^\s+([^:\r\n]+\.spec\.ts):\d+:\d+\s+›/);
    if (!match) continue;
    const spec = match[1].split(/[\\/]/).at(-1);
    if (seen.has(spec)) continue;
    seen.add(spec);
    order.push(spec);
  }
  return order;
}

export function assertListedSpecOrder(output, expected) {
  const observed = listedSpecOrder(output);
  if (observed.length !== expected.length || observed.some((name, index) => name !== expected[index])) {
    throw new Error(
      `Playwright did not collect the intended spec order. Expected ${JSON.stringify(expected)}, ` +
      `observed ${JSON.stringify(observed)}. No browser result may be counted.`,
    );
  }
  return observed;
}
